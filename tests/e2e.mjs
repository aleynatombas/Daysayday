import { call, model, sql, env } from "./harness.mjs";
const U = { a: "00000000-0000-0000-0000-0000000000a1", b: "00000000-0000-0000-0000-0000000000b1", c: "00000000-0000-0000-0000-0000000000c1" };
sql(`delete from auth.users; insert into auth.users(id,email) values ('${U.a}','a'),('${U.b}','b'),('${U.c}','c');
     insert into profiles(id,name,character) values ('${U.a}','Ada','daysy'),('${U.b}','Bora','charlie'),('${U.c}','Cem','ivy');`);
const today = sql("select billing_today()");
const msgs = [{ role: "user", content: "Bugün sunumum vardı" }, { role: "assistant", content: "Nasıl geçti?" }];
const W = (who, req, extra = {}) => call(who, { action: "write", messages: msgs, character: extra.character || "daysy", day: extra.day || today, request_id: req, by_friend: { daysy: msgs } });
const chat = (who, character) => call(who, { action: "chat", messages: [], character, today });
let pass = 0, fail = 0;
const ok = (name, cond, info = "") => { cond ? pass++ : fail++; console.log(`${cond ? "OK  " : "FAIL"} ${name}${info ? "  · " + info : ""}`); };
const used = fn => { const b = model.calls; return fn().then(r => ({ r, calls: model.calls - b })); };
const setPay = on => sql(`update app_settings set value='${on}'::jsonb where key='payments_enabled'`);

// --- Bayrak KAPALI: her şey eskisi gibi
setPay(false);
let x = await used(() => W(U.a, "k1"));
ok("kapalı: sayfa yazılır, modele gider", x.r.status === 200 && x.calls === 1 && !x.r.body.saved, `status=${x.r.status} calls=${x.calls}`);
x = await used(() => W(U.a, "k2"));
ok("kapalı: ikinci sayfa da yazılır (eski davranış)", x.r.status === 200 && x.calls === 1);
ok("kapalı: sunucu sayfayı kaydetmez, uygulama kaydeder", sql(`select count(*) from entries where user_id='${U.a}'`) === "0");
x = await used(() => chat(U.c, "charlie"));
ok("kapalı: Charlie herkese açık", x.r.status === 200 && x.calls === 1);
x = await call(U.a, { action: "billing" });
ok("kapalı: billing → enabled:false", x.body.enabled === false);
x = await call(U.a, { action: "checkout", sku: "page_1" });
ok("kapalı: ödeme ekranı/akışı yok", x.status === 403 && x.body.error === "payments_off");

// --- Bayrak AÇIK
setPay(true);
x = await used(() => chat(U.a, "daysy"));
ok("açık: bedava karakter (Daysy) modele gider", x.r.status === 200 && x.calls === 1);
x = await used(() => W(U.a, "a1"));
ok("açık: günün ilk sayfası modele gider ve kaydolur", x.r.status === 200 && x.calls === 1 && x.r.body.kind === "free", `kind=${x.r.body.kind}`);
ok("açık: sayfa veritabanında", sql(`select title from entries where user_id='${U.a}' and day='${today}'`).startsWith("Sayfa"));
x = await used(() => W(U.a, "a1"));
ok("aynı istek tekrar: modele gitmez, hak düşmez", x.r.status === 200 && x.calls === 0 && x.r.body.kind === "done" && sql(`select count(*) from page_ledger where user_id='${U.a}'`) === "1");
x = await used(() => W(U.a, "a2"));
ok("ikinci sayfa, kredisiz/aboneliksiz: modele gitmez", x.r.status === 402 && x.r.body.gate === "page" && x.calls === 0, `status=${x.r.status} gate=${x.r.body.gate} calls=${x.calls}`);
x = await call(U.a, { action: "checkout", sku: "page_4" });
ok("dikiş: geliştirme hakkı kapalıyken ödeme açılmaz", x.status === 503 && x.body.error === "checkout_unavailable" && sql(`select coalesce(sum(page_credits),0) from billing_accounts where user_id='${U.a}'`) === "0");
env.DEV_GRANTS = "on";
x = await call(U.a, { action: "checkout", sku: "page_4" });
ok("dört sayfalık paket dört kredi yazar", x.body.granted === true && sql(`select page_credits from billing_accounts where user_id='${U.a}'`) === "4");
model.fail = true;
x = await used(() => W(U.a, "a3"));
model.fail = false;
ok("başarısız yazım hak düşürmez", x.r.status !== 200 && sql(`select page_credits from billing_accounts where user_id='${U.a}'`) === "4" && sql(`select count(*) from page_ledger where user_id='${U.a}'`) === "1", `status=${x.r.status}`);
x = await used(() => W(U.a, "a3"));
ok("ikinci sayfa krediyle yazılır, bir kredi düşer", x.r.status === 200 && x.r.body.kind === "credit" && sql(`select page_credits from billing_accounts where user_id='${U.a}'`) === "3");
x = await used(() => W(U.a, "a3"));
ok("krediyle yazılan istek tekrar gelirse yine bir kez düşer", x.calls === 0 && sql(`select page_credits from billing_accounts where user_id='${U.a}'`) === "3");
x = await used(() => chat(U.a, "charlie"));
ok("abone değil, Charlie kilitli: modele gitmez", x.r.status === 402 && x.r.body.gate === "charlie" && x.calls === 0);
x = await call(U.a, { action: "checkout", sku: "charlie_once" });
x = await used(() => chat(U.a, "charlie"));
ok("Charlie 149 TL ile kalıcı açılır", x.r.status === 200 && x.calls === 1);

// abone
x = await call(U.b, { action: "checkout", sku: "plan_month" });
ok("aylık abonelik", x.body.granted === true);
x = await used(() => chat(U.b, "charlie"));
ok("abone: Charlie açık", x.r.status === 200 && x.calls === 1);
let s1 = await used(() => W(U.b, "b1")), s2 = await used(() => W(U.b, "b2")), s3 = await used(() => W(U.b, "b3"));
ok("abone: iki sayfa modele gider", s1.r.body.kind === "sub" && s2.r.body.kind === "sub" && s1.calls + s2.calls === 2);
ok("abone: üçüncü sayfa modele gitmez", s3.r.status === 402 && s3.r.body.gate === "page_sub" && s3.calls === 0);
ok("abone: sayfalar kredi düşmez", sql(`select coalesce((select page_credits from billing_accounts where user_id='${U.b}'),0)`) === "0");
x = await call(U.b, { action: "checkout", sku: "page_1" });
ok("aboneye 49 TL'lik sayfa satılmaz", x.status === 409 && x.body.error === "not_for_subscribers");
sql(`update subscriptions set current_period_end = now() - interval '1 second' where user_id='${U.b}'`);
x = await used(() => chat(U.b, "charlie"));
ok("abonelik bitti, kalıcı satın alma yok: Charlie kapanır (modele gitmez)", x.r.status === 402 && x.r.body.gate === "charlie" && x.calls === 0);
x = await call(U.b, { action: "billing" });
ok("abonelik bitti: durum", x.body.sub_active === false && x.body.has_charlie === false);
x = await call(U.c, { action: "checkout", sku: "plan_year" });
ok("yıllık kayıt on iki aylık dönem açar", sql(`select (current_period_end - now() between interval '364 days' and interval '366 days') from subscriptions where user_id='${U.c}'`) === "t");
x = await call(U.a, { action: "billing" });
ok("fiyatlar tek sabitten gelir", x.body.products.plan_year.kurus === 499000 && x.body.products.page_4.credits === 4, JSON.stringify(x.body.products));
env.DEV_GRANTS = undefined;
console.log(`\n${pass} geçti, ${fail} kaldı`);
